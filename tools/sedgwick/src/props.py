def corner(h, v, hx_from):
    """Join a horizontal fence run with a vertical one (fence turns south)."""
    g = blank()
    for y in range(16):
        for x in range(16):
            a = h[y][x] if x <= hx_from else 0
            b = v[y][x] if y >= 4 else 0
            g[y][x] = b or a
    return g


